const defaults = {
  runKey: 'Software\\Microsoft\\Windows\\CurrentVersion\\Run',
  approvalKey: 'Software\\Microsoft\\Windows\\CurrentVersion\\Explorer\\StartupApproved\\Run',
  valueName: 'Mashiro.Desktop',
  executableFilename: '${APP_EXECUTABLE_FILENAME}'
}

function assertNsisRegistryLiteral(value) {
  if (!/^[A-Za-z0-9 ._\\-]+$/.test(value)) throw new Error('PACKAGING_UNSAFE_REGISTRY_LITERAL')
}

export function renderLoginCleanupNsis(options = {}) {
  const { runKey, approvalKey, valueName, executableFilename } = { ...defaults, ...options }
  for (const value of [runKey, approvalKey, valueName]) assertNsisRegistryLiteral(value)
  if (
    executableFilename !== defaults.executableFilename &&
    (!/^[A-Za-z0-9 ._-]+\.exe$/i.test(executableFilename) || executableFilename.length > 180)
  )
    throw new Error('PACKAGING_UNSAFE_EXECUTABLE_FILENAME')
  return [
    '!macro MashiroRemoveOwnedLogin',
    '  Push $0',
    '  Push $1',
    '  Push $2',
    '  Push $3',
    '  Push $4',
    '  Push $5',
    '  Push $6',
    '  Push $7',
    '  Push $8',
    '  Push $9',
    '  Push $R0',
    '  Push $R1',
    '  Push $R2',
    '  Push $R3',
    '  Push $R4',
    '  Push $R5',
    '  Push $R6',
    '  Push $R7',
    '  Push $R8',
    '  Push $R9',
    `  Push "${runKey}"`,
    `  Push "${approvalKey}"`,
    `  Push "${valueName}"`,
    '  Call un.MashiroRemoveOwnedLogin',
    '  Pop $R9',
    '  Pop $R8',
    '  Pop $R7',
    '  Pop $R6',
    '  Pop $R5',
    '  Pop $R4',
    '  Pop $R3',
    '  Pop $R2',
    '  Pop $R1',
    '  Pop $R0',
    '  Pop $9',
    '  Pop $8',
    '  Pop $7',
    '  Pop $6',
    '  Pop $5',
    '  Pop $4',
    '  Pop $3',
    '  Pop $2',
    '  Pop $1',
    '  Pop $0',
    '!macroend',
    '',
    'Function un.MashiroRemoveOwnedLogin',
    '  Pop $R2',
    '  Pop $R1',
    '  Pop $R0',
    '  StrCpy $0 0',
    '  StrCpy $4 0',
    '  StrCpy $5 0',
    '  StrCpy $8 0',
    '  StrCpy $9 0',
    '  StrCpy $R5 0',
    '  StrCpy $R9 0',
    `  StrCpy $R3 '"$INSTDIR\\${executableFilename}" --mashiro-login'`,
    '  StrLen $R4 $R3',
    '  IntOp $R4 $R4 + 1',
    '  IntOp $R4 $R4 * ${NSIS_CHAR_SIZE}',
    '  ${If} $R4 > 4096',
    '    Goto mashiro_login_cleanup_done',
    '  ${EndIf}',
    "  System::Call 'advapi32::RegOpenKeyExW(p 0x80000001, w R0, i 0, i 0x103, *p .r0) i .r1'",
    '  ${If} $1 != 0',
    '    Goto mashiro_login_cleanup_done',
    '  ${EndIf}',
    "  System::Call 'advapi32::RegQueryValueExW(p r0, w R2, p 0, *i .r2, p 0, *i .r3) i .r1'",
    '  ${If} $1 != 0',
    '  ${OrIf} $2 != 1',
    '  ${OrIf} $3 != $R4',
    '    Goto mashiro_login_cleanup_done',
    '  ${EndIf}',
    '  IntOp $R7 $3 + ${NSIS_CHAR_SIZE}',
    '  System::Alloc $R7',
    '  Pop $4',
    '  ${If} $4 == 0',
    '    Goto mashiro_login_cleanup_done',
    '  ${EndIf}',
    "  System::Call 'kernel32::RtlZeroMemory(p r4, i R7)'",
    "  System::Call 'advapi32::RegQueryValueExW(p r0, w R2, p 0, *i .r2, p r4, *i R4R7) i .r1'",
    '  ${If} $1 != 0',
    '  ${OrIf} $2 != 1',
    '  ${OrIf} $R7 != $R4',
    '    Goto mashiro_login_cleanup_done',
    '  ${EndIf}',
    '  System::Alloc $R4',
    '  Pop $R9',
    '  ${If} $R9 == 0',
    '    Goto mashiro_login_cleanup_done',
    '  ${EndIf}',
    "  System::Call 'kernel32::lstrcpyW(p R9, w R3)'",
    "  System::Call 'msvcrt::memcmp(p r4, p R9, i R4) i .r1 ? c'",
    '  ${If} $1 != 0',
    '    Goto mashiro_login_cleanup_done',
    '  ${EndIf}',
    "  System::Call 'advapi32::RegOpenKeyExW(p 0x80000001, w R1, i 0, i 0x103, *p .r5) i .r1'",
    '  ${If} $1 == 0',
    "    System::Call 'advapi32::RegQueryValueExW(p r5, w R2, p 0, *i .r6, p 0, *i .r7) i .r1'",
    '    ${If} $1 == 0',
    '    ${AndIf} $6 == 3',
    '    ${AndIf} $7 <= 4096',
    '      IntOp $R7 $7 + 1',
    '      System::Alloc $R7',
    '      Pop $8',
    '      ${If} $8 != 0',
    "        System::Call 'kernel32::RtlZeroMemory(p r8, i R7)'",
    "        System::Call 'advapi32::RegQueryValueExW(p r5, w R2, p 0, *i .r6, p r8, *i r7R7) i .r1'",
    '        ${If} $1 == 0',
    '        ${AndIf} $6 == 3',
    '        ${AndIf} $R7 == $7',
    '          StrCpy $R5 1',
    '        ${EndIf}',
    '      ${EndIf}',
    '    ${EndIf}',
    '  ${EndIf}',
    "  System::Call 'kernel32::RtlZeroMemory(p r4, i R4)'",
    '  StrCpy $R7 $R4',
    "  System::Call 'advapi32::RegQueryValueExW(p r0, w R2, p 0, *i .R6, p r4, *i R7R7) i .r1'",
    '  ${If} $1 != 0',
    '  ${OrIf} $R6 != 1',
    '  ${OrIf} $R7 != $R4',
    '    Goto mashiro_login_cleanup_done',
    '  ${EndIf}',
    "  System::Call 'msvcrt::memcmp(p r4, p R9, i R4) i .r1 ? c'",
    '  ${If} $1 != 0',
    '    Goto mashiro_login_cleanup_done',
    '  ${EndIf}',
    '  ${If} $R5 == 1',
    '    IntOp $R7 $7 + 1',
    '    System::Alloc $R7',
    '    Pop $9',
    '    ${If} $9 == 0',
    '      Goto mashiro_login_cleanup_done',
    '    ${EndIf}',
    "    System::Call 'kernel32::RtlZeroMemory(p r9, i R7)'",
    "    System::Call 'advapi32::RegQueryValueExW(p r5, w R2, p 0, *i .R6, p r9, *i r7R7) i .r1'",
    '    ${If} $1 != 0',
    '    ${OrIf} $R6 != 3',
    '    ${OrIf} $R7 != $7',
    '      Goto mashiro_login_cleanup_done',
    '    ${EndIf}',
    "    System::Call 'msvcrt::memcmp(p r8, p r9, i r7) i .R8 ? c'",
    '    ${If} $R8 != 0',
    '      Goto mashiro_login_cleanup_done',
    '    ${EndIf}',
    '  ${EndIf}',
    "  System::Call 'advapi32::RegDeleteValueW(p r0, w R2) i .r1'",
    '  ${If} $1 != 0',
    '    Goto mashiro_login_cleanup_done',
    '  ${EndIf}',
    "  System::Call 'advapi32::RegQueryValueExW(p r0, w R2, p 0, *i .R6, p 0, *i .R7) i .r1'",
    '  ${If} $1 != 2',
    '    Goto mashiro_login_cleanup_done',
    '  ${EndIf}',
    '  ${If} $R5 == 1',
    '    IntOp $R7 $7 + 1',
    "    System::Call 'kernel32::RtlZeroMemory(p r9, i R7)'",
    '    StrCpy $R7 $7',
    "    System::Call 'advapi32::RegQueryValueExW(p r5, w R2, p 0, *i .R6, p r9, *i R7R7) i .r1'",
    '    ${If} $1 == 0',
    '    ${AndIf} $R6 == 3',
    '    ${AndIf} $R7 == $7',
    "      System::Call 'msvcrt::memcmp(p r8, p r9, i r7) i .R8 ? c'",
    '      ${If} $R8 == 0',
    "        System::Call 'advapi32::RegDeleteValueW(p r5, w R2) i .r1'",
    '        ${If} $1 == 0',
    "          System::Call 'advapi32::RegQueryValueExW(p r5, w R2, p 0, *i .R6, p 0, *i .R7) i .r1'",
    '        ${EndIf}',
    '      ${EndIf}',
    '    ${EndIf}',
    '  ${EndIf}',
    'mashiro_login_cleanup_done:',
    '  ${If} $9 != 0',
    '    System::Free $9',
    '  ${EndIf}',
    '  ${If} $8 != 0',
    '    System::Free $8',
    '  ${EndIf}',
    '  ${If} $5 != 0',
    "    System::Call 'advapi32::RegCloseKey(p r5)'",
    '  ${EndIf}',
    '  ${If} $4 != 0',
    '    System::Free $4',
    '  ${EndIf}',
    '  ${If} $R9 != 0',
    '    System::Free $R9',
    '  ${EndIf}',
    '  ${If} $0 != 0',
    "    System::Call 'advapi32::RegCloseKey(p r0)'",
    '  ${EndIf}',
    'FunctionEnd',
    ''
  ].join('\n')
}

export function renderOwnedFilesNsis(owned, directories, loginOptions) {
  const lines = [
    renderLoginCleanupNsis(loginOptions),
    '!macro customRemoveFiles',
    '  SetOutPath $TEMP'
  ]
  for (const [index, path] of owned.entries()) {
    const windows = path.replaceAll('/', '\\')
    const done = 'mashiro_remove_done_' + index
    lines.push(
      `  IfFileExists "$INSTDIR\\${windows}" 0 ${done}`,
      '  ClearErrors',
      `  Delete "$INSTDIR\\${windows}"`,
      `  IfErrors 0 ${done}`,
      '  Abort "Mashiro program file is busy; data has been preserved."',
      done + ':'
    )
  }
  lines.push(
    '  Delete "$INSTDIR\\${UNINSTALL_FILENAME}"',
    '  Push $R9',
    '  ${IfNot} ${isUpdated}',
    '    !insertmacro MashiroRemoveOwnedLogin',
    '  ${EndIf}',
    '  Pop $R9'
  )
  for (const directory of directories.sort((a, b) => b.length - a.length))
    lines.push(`  RMDir "$INSTDIR\\${directory.replaceAll('/', '\\')}"`)
  lines.push('  RMDir "$INSTDIR"', '!macroend', '')
  return lines.join('\n')
}
