    '  ${EndIf}',
    '  ${If} $8 != 0',
    '    System::Free $8',
    '  ${EndIf}',
    '  ${If} $5 != 0',
    "    System::Call 'advapi32::RegCloseKey(p r5)'",
    '  ${EndIf}',
