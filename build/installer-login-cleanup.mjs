export function renderOwnedFilesNsis(owned, directories, loginOptions = {}) {
  const resolvedLogin = { ...defaults, ...loginOptions }
  const lines = [
    '!ifdef BUILD_UNINSTALLER',
    '!include LogicLib.nsh',
    renderLoginCleanupNsis(resolvedLogin),
    renderLoginRemovalCallMacro({
      macroName: 'MashiroRemoveOwnedLegacyLogin',
      runKey: resolvedLogin.runKey,
      approvalKey: resolvedLogin.approvalKey,
      valueName: resolvedLogin.legacyValueName
    }),
    renderToastCleanupNsis(resolvedLogin),
    '!macro customRemoveFiles',
    '  SetOutPath $TEMP'
  ]
  for (const [index, path] of owned.entries()) {
    const windows = path.replaceAll('/', '\\')
    const done = 'mashiro_remove_done_' + index
    lines.push(
      `  IfFileExists "$INSTDIR\\${windows}" 0 ${done}`,
      '  ClearErrors',
      `  Delete "$INSTDIR\\${windows}"`,
      `  IfErrors 0 ${done}`,
      '  Abort "Mashiro program file is busy; data has been preserved."',
      done + ':'
    )
  }
  lines.push(
    '  Delete "$INSTDIR\\${UNINSTALL_FILENAME}"',
    '  Push $R9',
    '  ${IfNot} ${isUpdated}',
    '    !insertmacro MashiroRemoveOwnedLogin',
    '    !insertmacro MashiroRemoveOwnedLegacyLogin',
    '    !insertmacro MashiroRemoveOwnedToastActivators',
    '  ${EndIf}',
    '  Pop $R9'
  )
  for (const directory of directories.sort((a, b) => b.length - a.length))
    lines.push(`  RMDir "$INSTDIR\\${directory.replaceAll('/', '\\')}"`)
  lines.push(
    '  RMDir "$INSTDIR"',
    '!macroend',
    '!else',
    '!include LogicLib.nsh',
    renderLoginMigrationNsis(resolvedLogin),
    '!macro customInstall',
    '  !insertmacro MashiroMigrateOwnedLegacyLogin',
    '!macroend',
    '!endif',
    ''
  )
  return lines.join('\n')
}
