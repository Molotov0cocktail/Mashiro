    '  IntOp $R4 $R4 + 1',
    '  IntOp $R4 $R4 * ${NSIS_CHAR_SIZE}',
    '  ${If} $R4 > 4096',
    '    Goto mashiro_login_cleanup_done',
    '  ${EndIf}',
