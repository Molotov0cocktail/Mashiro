    '    ${AndIf} $R7 == $7',
    "      System::Call 'msvcrt::memcmp(p r8, p r9, i r7) i .R8 ? c'",
    '      ${If} $R8 == 0',
    "        System::Call 'advapi32::RegDeleteValueW(p r5, w R2) i .r1'",
    '        ${If} $1 == 0',
